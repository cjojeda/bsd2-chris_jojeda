"""Consistent local snapshots; never copy a live SQLite WAL file by hand."""
from datetime import datetime
from contextlib import closing
from pathlib import Path
import sqlite3

def automatic_backup(db, reason="startup", keep=20):
    if str(db.path) == ":memory:":
        return None
    folder = Path(db.path).parent / "backups"
    folder.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now().strftime("%Y-%m-%d_%H%M%S_%f")
    if reason == "startup" and any(folder.glob(f"auto-sadi-{stamp[:10]}-startup-*.sqlite3")):
        return None
    target = folder / f"auto-sadi-{stamp[:10]}-{reason}-{stamp[11:]}.sqlite3"
    try:
        with closing(sqlite3.connect(target)) as destination:
            db.connection.backup(destination)
            if destination.execute("PRAGMA integrity_check").fetchone()[0] != "ok":
                raise ValueError("La copia automática no superó la verificación de integridad.")
            if destination.execute("PRAGMA foreign_key_check").fetchone():
                raise ValueError("La copia automática contiene referencias inválidas.")
    except BaseException:
        target.unlink(missing_ok=True)
        raise
    # Only files generated by this function are considered for local retention.
    snapshots = sorted(folder.glob("auto-sadi-*.sqlite3"), key=lambda p: p.stat().st_mtime, reverse=True)
    for old in snapshots[keep:]:
        old.unlink(missing_ok=True)
    return target
