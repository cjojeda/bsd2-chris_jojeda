import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { mkdtemp, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

// Run against an isolated --data-dir containing the demo. Never a real business.
const base=process.env.SOU_LINDA_TEST_URL??'http://127.0.0.1:8765';
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH??'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
page.setDefaultTimeout(15000);
const failures=[];page.on('pageerror',error=>failures.push(error.message));
const folder=await mkdtemp(join(tmpdir(),'sou-linda-browser-finance-'));
try{
  await page.goto(base);
  await page.getByRole('button',{name:'Resumen',exact:true}).waitFor();
  await page.getByText('Estás explorando datos de ejemplo.',{exact:false}).waitFor();
  const read=path=>page.evaluate(async url=>{const response=await fetch(url,{cache:'no-store'});if(!response.ok)throw new Error(`HTTP ${response.status}`);return response.json();},path);
  const before=await read('/api/snapshot');
  assert(before.settings.some(row=>row.key==='demo'&&row.value==='true'),'La prueba requiere una base marcada como demostración');
  const quantum=before.settings.some(row=>row.key==='currency'&&row.value==='PYG')?100n:1n;
  const variant=before.variants.find(row=>row.active&&row.available>0&&row.stock>0);
  assert(variant,'Debe haber stock de prueba disponible');
  await page.getByRole('button',{name:'Punto de venta',exact:true}).click();
  await page.getByLabel('Buscar producto para vender').waitFor({state:'visible'});
  await page.waitForFunction(()=>!document.querySelector('input[aria-label="Buscar producto para vender"]')?.disabled);
  const clear=page.getByRole('button',{name:'Vaciar borrador',exact:true});
  if(await clear.isEnabled()){page.once('dialog',dialog=>dialog.accept());await clear.click();await page.getByText('Elegí una prenda para empezar',{exact:true}).waitFor();}
  await page.getByLabel('Buscar producto para vender').fill(variant.sku);
  await page.locator('button.catalog-card:not([disabled])').first().click();
  await page.getByLabel(`Precio unitario de ${variant.sku}`,{exact:true}).fill('2000');
  await page.getByLabel('Canal de venta',{exact:true}).selectOption('Instagram');
  await page.getByLabel('Cobro al completar',{exact:true}).selectOption('Efectivo');
  const date=await page.getByLabel('Fecha del pedido',{exact:true}).inputValue();
  const monthlyBefore=await read(`/api/reports/monthly?month=${date.slice(0,7)}`);
  await page.getByText('Promoción, comisión y costos directos',{exact:true}).click();
  await page.getByLabel('Tipo de descuento',{exact:true}).selectOption('percent');
  await page.getByLabel('Descuento (%)',{exact:true}).fill('10');
  await page.getByLabel('Comisión del cobro (%)',{exact:true}).fill('3');
  await page.getByLabel(/^Packaging \(/).fill('50');
  await page.getByLabel(/^Envío asumido \(/).fill('100');
  await page.getByLabel('Envío y packaging se pagan al completar',{exact:true}).check();
  const cpp=Number(((2n*BigInt(variant.inventoryValue)+BigInt(variant.stock)*quantum)/(2n*BigInt(variant.stock)*quantum))*quantum);
  const expected={total:180000,cost:cpp,commission:5400,shipping:10000,packaging:5000};
  const expectedProfit=expected.total-expected.cost-expected.commission-expected.shipping-expected.packaging;
  const saleResponse=page.waitForResponse(response=>new URL(response.url()).pathname==='/api/sales'&&response.request().method()==='POST');
  await page.getByRole('button',{name:'Completar venta',exact:true}).click();
  const response=await saleResponse;assert(response.ok(),'El servidor debe confirmar la venta');const sale=await response.json();
  await page.getByRole('dialog',{name:'Venta registrada',exact:true}).waitFor();
  assert.equal(sale.total,expected.total);assert.equal(sale.discount,20000);assert.equal(sale.costTotal,expected.cost);assert.equal(sale.commissionCost,expected.commission);assert.equal(sale.shippingCost,expected.shipping);assert.equal(sale.packagingCost,expected.packaging);
  assert.equal(sale.total-sale.costTotal-sale.commissionCost-sale.shippingCost-sale.packagingCost,expectedProfit);
  const after=await read('/api/snapshot');const afterVariant=after.variants.find(row=>row.id===variant.id);
  assert.equal(afterVariant.stock,variant.stock-1);assert.equal(afterVariant.inventoryValue,variant.inventoryValue-cpp);
  const monthlyAfter=await read(`/api/reports/monthly?month=${date.slice(0,7)}`);
  assert.equal(monthlyAfter.net_profit_cents-monthlyBefore.net_profit_cents,expectedProfit,'El resultado mensual debe reconocer el margen real exacto');
  await page.getByRole('button',{name:'Cerrar ventana'}).click();
  await page.getByRole('button',{name:'Datos y respaldos',exact:true}).click();
  const downloadPromise=page.waitForEvent('download');await page.getByRole('button',{name:'Descargar respaldo JSON',exact:true}).click();
  const download=await downloadPromise;const backupPath=join(folder,'business.json');await download.saveAs(backupPath);
  const backup=JSON.parse(await readFile(backupPath,'utf8'));assert(backup,'El backup debe ser JSON válido');
  const chooserPromise=page.waitForEvent('filechooser');await page.getByRole('button',{name:'Elegir respaldo JSON',exact:true}).click();
  await (await chooserPromise).setFiles(backupPath);
  await page.getByRole('dialog',{name:'¿Reemplazar todos los datos?',exact:true}).waitFor();
  const restoreResponse=page.waitForResponse(response=>new URL(response.url()).pathname==='/api/backup/restore'&&response.request().method()==='POST');
  await page.getByRole('button',{name:'Sí, reemplazar datos',exact:true}).click();
  const restored=await restoreResponse;assert(restored.ok(),'La restauración confirmada debe completar');
  await page.getByText('Base restaurada y validada.',{exact:true}).waitFor();
  const final=await read('/api/snapshot');
  for(const collection of ['products','variants','customers','sales','expenses','movements','payments','cashClosings'])assert.deepEqual(final[collection],after[collection],`La restauración conserva ${collection}`);
  const finalReport=await read(`/api/reports/monthly?month=${date.slice(0,7)}`);assert.deepEqual(finalReport,monthlyAfter,'El backup conserva todos los resultados financieros');
  await page.getByRole('button',{name:'Punto de venta',exact:true}).click();await page.getByText('Elegí una prenda para empezar',{exact:true}).waitFor();
  assert.deepEqual(failures,[]);
  console.log(JSON.stringify({result:'PASS',checks:['venta completada desde UI','descuento porcentual sin modificar CPP','comisión efectiva','envío y packaging','reducción de inventario y valor exactos','resultado mensual exacto','descarga JSON','restauración UI completa','persistencia de reportes tras restauración','POS habilitado con borrador vacío','sin errores JavaScript']}));
}finally{await browser.close();await rm(folder,{recursive:true,force:true});}
